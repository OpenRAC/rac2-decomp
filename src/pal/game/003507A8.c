/* Builds the menu system: clears its memory, constructs every menu screen in place, loads the resident data from disc and then initialises each screen (PAL). */
char *menu_system_init_pal(char *menu)
{
    int i;
    int size;
    char *end;
    int *clear = (int *)(menu + 4);
    char *pool_root;
    char *part0;
    char *part1;
    char *part2;
    char *part3;
    char *part4;
    char *part5;
    char *part6;
    char *part7;
    char *part8;
    char *part9;
    char *part10;
    char *part11;
    char *part12;
    char *part13;
    char *part14;
    char *part15;
    char *part16;
    char *part17;
    char *part18;
    char *part19;
    char *part20;
    char *part21;
    char *part22;
    char *part23;
    char *part24;
    char *part25;
    char *part26;
    char *part27;
    char *part28;
    char *part29;
    char *part30;
    for (i = 0x86F; i != -1; i--) {
        clear[0] = 0; clear[1] = 0; clear[2] = 0; clear[3] = 0;
        clear += 4;
    }
    pool_root = menu + 0x36F10;
    ui_return_self(pool_root);
    part0 = menu + 0x36F28;
    menu_init_level_parts_pal(part0);
    part1 = menu + 0x39160;
    menu_init_seven_labels_pal(part1);
    part2 = menu + 0x39620;
    menu_screen_large_init_parts_pal(part2);
    part3 = menu + 0x39BA0;
    menu_screen_init_parts_pal(part3);
    part4 = menu + 0x3A0B0;
    grid_menu_init_widgets_pal(part4);
    part5 = menu + 0x3A570;
    radial_menu_construct_pal(part5);
    part6 = menu + 0x3B030;
    list_screen_destroy_pal(part6);
    part7 = menu + 0x3B4C8;
    mission_screen_init_parts_pal(part7);
    part8 = menu + 0x3B7A8;
    map_screen_destroy_pal(part8);
    part9 = menu + 0x3BB08;
    frame_text_page_destroy_pal(part9);
    part10 = menu + 0x3C210;
    tab_menu_construct_pal(part10);
    part11 = menu + 0x3C530;
    menu_init_widgets_pal(part11);
    part12 = menu + 0x3C898;
    simple_list_page_destroy_pal(part12);
    part13 = menu + 0x3CBD0;
    small_menu_construct_pal(part13);
    part14 = menu + 0x3CDF8;
    menu_return_object(part14);
    part15 = menu + 0x3CF50;
    mission_screen_shutdown_pal(part15);
    part16 = menu + 0x3D288;
    single_toggle_b_destroy_pal(part16);
    part17 = menu + 0x3D568;
    onoff_menu_destroy_pal(part17);
    part18 = menu + 0x3D848;
    four_option_menu_destroy_pal(part18);
    part19 = menu + 0x3DB28;
    two_toggle_a_destroy_pal(part19);
    part20 = menu + 0x3DE98;
    single_toggle_a_destroy_pal(part20);
    part21 = menu + 0x3E178;
    map_screen_destroy_prompt_bar_pal(part21);
    part22 = menu + 0x3E458;
    screen_adjust_menu_destroy_pal(part22);
    part23 = menu + 0x3E738;
    menu_pass_through_handle(part23);
    part24 = menu + 0x3E810;
    list_menu_construct_parts(part24);
    part25 = menu + 0x3EA78;
    small_list_menu_construct_pal(part25);
    part26 = menu + 0x3EC00;
    two_toggle_b_destroy_pal(part26);
    part27 = menu + 0x3EEE0;
    single_toggle_c_destroy_pal(part27);
    part28 = menu + 0x3F1C0;
    single_toggle_d_destroy_pal(part28);
    part29 = menu + 0x3F4A0;
    list_page_destroy_pal(part29);
    part30 = menu + 0x3F860;
    title_screen_destroy(part30);
    size = 0x3FBD0;
    end = menu + size;
    g_resident_data_base[0] = menu;
    *(char **)menu = (char *)(((int)end + 3) & -4);
    *(int *)(menu + 0x3FA80) = size;
    load_read_disc_with_pause_pal(menu + 0x8710, g_copy_setup_data.data + g_copy_setup_data.offset, g_copy_setup_data.size);
    table_relocate_entries(menu + 0x8710);
    pool_init_cells(pool_root, 16, menu + 4, 0x8700);
    records_screen_init(part0, menu, pool_root);
    *(int *)(menu + 0x3FA84) = 0;
    *(int *)(menu + 0x3FA88) = 0;
    *(int *)(menu + 0x3FA8C) = 0;
    *(int *)(menu + 0x3FA90) = 0;
    menu_page_construct_with_rows_pal(part1, pool_root);
    item_grid_menu_init_pal(part2, pool_root);
    selection_menu_init_pal(part3, pool_root);
    grid_menu_construct_pal(part4, pool_root);
    radial_menu_init_pal(part5, pool_root);
    list_screen_init_pal(part6, pool_root);
    grid_menu_init_pal(part13, pool_root);
    mission_screen_init_pal(part7, pool_root);
    tab_menu_init_pal(part10, pool_root);
    item_menu_construct_pal(part11, pool_root);
    map_screen_init_pal(part8, pool_root);
    info_panel_init_pal(part9, pool_root);
    simple_page_init_pal(part12, pool_root);
    menu_clear_entries(part14);
    title_screen_init_labels(part30, pool_root);
    two_toggle_b_init_pal(part16, pool_root);
    onoff_menu_b_init_pal(part17, pool_root);
    popup_init_pal(part15, pool_root);
    two_toggle_b_init_pal(part16, pool_root);
    onoff_menu_b_init_pal(part17, pool_root);
    two_toggle_a_init_pal(part18, pool_root);
    audio_menu_init_pal(part19, pool_root);
    single_toggle_a_init_pal(part20, pool_root);
    screen_adjust_menu_init_pal(part21, pool_root);
    onoff_menu_init_pal(part22, pool_root);
    list_menu_reset_attach_items_pal(part23, pool_root);
    small_list_menu_init_pal(part25, pool_root);
    list_menu_init_pal(part24, pool_root);
    single_toggle_c_init_pal(part26, pool_root);
    single_toggle_d_init_pal(part27, pool_root);
    single_toggle_e_init_pal(part28, pool_root);
    list_page_init_pal(part29, pool_root);
    *(int *)(menu + 0x3FA9C) = 0;
    *(int *)(menu + 0x3FAA0) = 0;
    *(int *)(menu + 0x3FAA4) = 0;
    memset(menu + 0x3FAA8, 0, 32);
    memset(menu + 0x3FAC8, 0, 256);
    return menu;
}

