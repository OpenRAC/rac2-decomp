/* func_PAL_00348868, the PAL copy of func_00346710: the same C, where the later fields and widgets
 * move, the +0x2C0 widget gets a 0.8 scale and two more fields, the text id changes, and the
 * shared 0x60241700 colour lives in a local, so it takes its stack slot ahead of the later widgets. */
#include "common.h"

extern char *GetLocalizedString();
extern int *object_get_fourth_field();
extern void object_set_second_float4(s32, f32, f32, f32, f32);
extern void object_init_derived_arrays();
extern void object_set_helper_result();
extern void object_init_derived_b();
extern void object_set_first_pair();
extern void object_set_second_pair();
extern void object_init_derived_c();
extern void hud_init_widget_defaults_pal();
extern void hud_set_widget_field_a();
extern void hud_set_widget_field_b();
extern void func_PAL_003388E8();
extern void meter_set_value();
extern void widget_store_field();
extern void widget_set_pos_y();
extern void text_set_alignment();
extern void *ui_return_second_arg();
extern void *pool_alloc_cell();
extern s32 UpdateItemGridMenu_pal();
extern s32 g_resident_data_base;
extern s8 g_item_grid_array_init_b[];
extern s8 g_menu_frame_desc[];
extern s8 g_menu_backdrop_desc[];
extern s8 g_menu_icon_desc[];
extern s8 g_menu_widget_desc_second[];
extern s8 g_menu_widget_desc_first[];
extern s8 g_menu_panel_desc[];
extern s8 g_menu_widget_desc_fourth[];
extern s8 g_menu_extra_widget_desc[];
extern s8 g_item_grid_array_init_a[];
extern s8 g_menu_bar_desc[];
extern s8 g_menu_hud_label_desc[];
extern s8 g_item_grid_widget_defaults_a[];
extern s8 g_item_grid_widget_defaults_b[];

/* Initializes the item grid menu: sets its origin, builds its widgets with their colors and text, then runs one update. (PAL) */
void item_grid_menu_init_pal(s32 menu, s32 data) {
    s32 widget_4c;
    s32 widget_130;
    s32 widget_98;
    s32 widget_450;
    s32 widget_49c;
    s32 widget_e4;
    s32 widget_17c;
    s32 color;
    s32 widget_3c8;
    s32 label_210;
    s32 label_268;
    s32 label_2c0;
    s32 label_318;
    s32 label_370;
    s32 *color_ptr;
    s32 *color_ptr_b;
    s32 meter;
    s32 widget_404;
    s32 origin;

    (*(s32 *)((s8 *)(menu) + (0x4EC))) = data;
    if (data != 0) {
        origin = ui_return_second_arg(0x10, pool_alloc_cell(data));
        (*(s32 *)((s8 *)(menu) + (0x4E8))) = origin;
        (*(s32 *)((s8 *)(origin) + (4))) = 0;
        (*(s32 *)((s8 *)(origin) + (8))) = 0;
        (*(s32 *)((s8 *)(origin) + (0xC))) = 0;
        (*(s32 *)((s8 *)(origin) + (0))) = 0;
    }
    (*(s32 *)((s8 *)(menu) + (0x570))) = 1;
    (*(f32 *)((s8 *)((*(s32 *)((s8 *)(menu) + (0x4E8)))) + (0))) = 250.0f;
    widget_4c = menu + 0x4C;
    meter = menu + 0x1C8;
    widget_130 = menu + 0x130;
    widget_98 = menu + 0x98;
    (*(f32 *)((s8 *)((*(s32 *)((s8 *)(menu) + (0x4E8)))) + (4))) = 207.0f;
    widget_450 = menu + 0x450;
    object_init_derived_arrays(menu, g_menu_widget_desc_first, data);
    widget_49c = menu + 0x49C;
    object_init_derived_arrays(widget_4c, g_menu_widget_desc_second, data);
    object_init_derived_arrays(widget_130, g_menu_panel_desc, data);
    widget_e4 = menu + 0xE4;
    object_init_derived_arrays(widget_98, g_menu_widget_desc_fourth, data);
    widget_17c = menu + 0x17C;
    object_init_derived_arrays(widget_450, g_menu_extra_widget_desc, data);
    object_init_derived_arrays(widget_49c, g_item_grid_array_init_a, data);
    object_init_derived_b(meter, 0x20, 0, g_menu_bar_desc, data);
    widget_set_pos_y(meter, 5);
    func_PAL_003388E8(meter, 0x64);
    meter_set_value(meter, 0);
    object_set_first_pair(meter, 0x6049C1FF, 0x60001EFF);
    object_set_second_pair(meter, 0x50F0C070, 0x50F0C070);
    widget_3c8 = menu + 0x3C8;
    text_set_alignment(meter, 0x80000000);
    widget_store_field(meter, 0);
    widget_404 = menu + 0x404;
    object_init_derived_arrays(widget_e4, g_menu_frame_desc, data);
    label_210 = menu + 0x210;
    object_init_derived_arrays(widget_17c, g_item_grid_array_init_b, data);
    label_2c0 = menu + 0x2C0;
    label_268 = menu + 0x268;
    color_ptr = object_get_fourth_field(menu);
    label_318 = menu + 0x318;
    *color_ptr = 0x60442D00;
    color_ptr_b = object_get_fourth_field(widget_4c);
    label_370 = menu + 0x370;
    *color_ptr_b = 0x55F0C070;
    *(s32 *)object_get_fourth_field(widget_130) = 0x80FFDE8D;
    *(s32 *)object_get_fourth_field(widget_98) = 0x55F0C070;
    *(s32 *)object_get_fourth_field(widget_e4) = 0x80FFDE8D;
    color = 0x60241700;
    *(s32 *)object_get_fourth_field(widget_17c) = color;
    *(s32 *)object_get_fourth_field(widget_450) = 0x60442D00;
    *(s32 *)object_get_fourth_field(widget_49c) = 0x55F0C070;
    object_set_helper_result(menu, g_resident_data_base + 0x8710, 0x21);
    object_set_helper_result(widget_4c, g_resident_data_base + 0x8710, 0x22);
    object_set_helper_result(widget_130, g_resident_data_base + 0x8710, 0x28);
    object_set_helper_result(widget_98, g_resident_data_base + 0x8710, 0x23);
    object_set_helper_result(widget_e4, g_resident_data_base + 0x8710, 0x27);
    object_set_helper_result(widget_17c, g_resident_data_base + 0x8710, 0x2A);
    object_set_helper_result(widget_450, g_resident_data_base + 0x8710, 0x2C);
    object_set_helper_result(widget_49c, g_resident_data_base + 0x8710, 0x2B);
    (*(s32 *)((s8 *)(menu) + (0x574))) = 0;
    (*(s32 *)((s8 *)(menu) + (0x578))) = 0;
    object_init_derived_c(widget_3c8, g_menu_icon_desc, data);
    *(s32 *)object_get_fourth_field(widget_3c8) = 0x60F0F0B0;
    object_set_second_float4(widget_3c8, 32.0f, 32.0f, 0.0f, 0.0f);
    object_init_derived_arrays(widget_404, g_menu_backdrop_desc, data);
    *(s32 *)object_get_fourth_field(widget_404) = color;
    object_set_helper_result(widget_404, g_resident_data_base + 0x8710, 0x29);
    object_set_second_float4(widget_404, 1.0f, 1.0f, 0.0f, 0.0f);
    hud_init_widget_defaults_pal(label_210, g_menu_hud_label_desc, data);
    hud_init_widget_defaults_pal(label_268, g_menu_hud_label_desc, data);
    hud_set_widget_field_a(label_268, 1);
    hud_init_widget_defaults_pal(label_2c0, g_menu_hud_label_desc, data);
    hud_set_widget_field_a(label_2c0, 1);
    object_set_second_float4(label_2c0, 0.8f, 0.8f, 0.0f, 0.0f);
    (*(s32 *)((s8 *)(label_2c0) + (0x48))) = 1;
    (*(s32 *)((s8 *)(label_2c0) + (0x4C))) = 200;
    hud_init_widget_defaults_pal(label_318, g_item_grid_widget_defaults_a, data);
    hud_set_widget_field_a(label_318, 1);
    hud_init_widget_defaults_pal(label_370, g_item_grid_widget_defaults_b, data);
    hud_set_widget_field_a(label_370, 1);
    *(s32 *)object_get_fourth_field(label_210) = 0x80F0F0F0;
    *(s32 *)object_get_fourth_field(label_268) = 0x80F0F0F0;
    *(s32 *)object_get_fourth_field(label_2c0) = 0x80F0F0F0;
    *(s32 *)object_get_fourth_field(label_318) = 0x80F0F0F0;
    *(s32 *)object_get_fourth_field(label_370) = 0x80F0F0F0;
    hud_set_widget_field_b(label_210, GetLocalizedString(0xB62));
    hud_set_widget_field_b(label_268, menu + 0x4F0);
    hud_set_widget_field_b(label_2c0, menu + 0x530);
    UpdateItemGridMenu_pal(menu, 0);
}
