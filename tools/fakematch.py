#!/usr/bin/env python3
"""Track fakematch sites: code that matches retail but is not what the authors wrote.

  python3 tools/fakematch.py --write   # regenerate config/fakematch.tsv from the FAKEMATCH comments
  python3 tools/fakematch.py --check   # fail if the table and the comments disagree, or a site is not allowed

Every site carries a comment `/* FAKEMATCH: <what it does and why> */` on or above the line it
explains, as in rac1-decomp (docs/STYLE.md, config/fakematch.tsv). Unlike RAC1's scanner this one
tags nothing by itself: this repository's other allowed shapes (the HUD dead-test helpers, set-once
locals and the like) are owner rulings, not fakematches.

Fakematches are allowed only in the functions in ALLOWED and in helpers defined in their units (owner ruling, 13 November 2026: the last
five USA v1.01 functions, after compiler rules and plain source were exhausted; AGENTS.md), and in
any PAL or USA v2.00 function of its own (owner ruling, 14 November 2026: func_PAL_* and func_US2_*
functions, defined in src/pal/ or src/us2/).
"""
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TABLE = ROOT / "config/fakematch.tsv"
TAG = "FAKEMATCH:"
HEADER = ("# Code that matches retail but is not what the authors wrote. Generated by tools/fakematch.py.\n"
          "# file\tfunction\treason\n")
ALLOWED = {
    "func_0034CEA0",
    "func_002CC6B0",
    "func_L04_00417308",
    "func_L05_0042B2C0",
    "func_L17_003E8A58",
}
RELEASE_OWN = re.compile(r"^func_(?:PAL|US2)_\w+$")
DEFINITION = re.compile(r"^[A-Za-z_][^;{}=\n]*?\b(\w+)\s*\([^;{}]*\)\s*\{", re.M)
COMMENT_OR_STRING = re.compile(r'/\*.*?\*/|//[^\n]*|"(?:\\.|[^"\\\n])*"|\'(?:\\.|[^\'\\\n])*\'', re.S)


def blank(match: re.Match) -> str:
    """The match with every character but newlines replaced by a space, so offsets stay put."""
    return re.sub(r"[^\n]", " ", match.group(0))


def sources() -> list:
    out = subprocess.run(["git", "ls-files", "src/*.c", "src/**/*.c"], cwd=ROOT,
                         capture_output=True, text=True, check=True).stdout
    return sorted(set(out.split()))


def function_lines(text: str) -> list:
    """[(first line, last line, name)] of each function definition, 1-based."""
    masked = COMMENT_OR_STRING.sub(blank, text)
    found = []
    for m in DEFINITION.finditer(masked):
        depth, i = 1, m.end()
        while i < len(masked) and depth:
            depth += (masked[i] == "{") - (masked[i] == "}")
            i += 1
        found.append((masked.count("\n", 0, m.start()) + 1, masked.count("\n", 0, i) + 1, m.group(1)))
    return found


def function_at(functions: list, line: int) -> str:
    for first, last, name in functions:
        if first <= line <= last:
            return name
    return "-"


def rows_of(rel: str, text: str) -> list:
    """[(file, function, reason)] for every FAKEMATCH comment in this file."""
    functions = function_lines(text)
    rows = []
    for number, line in enumerate(text.split("\n"), 1):
        at = line.find(TAG)
        if at < 0:
            continue
        reason = " ".join(line[at + len(TAG):].split("*/")[0].split()).rstrip(".")
        # A comment above a function's first line belongs to that function.
        rows.append((rel, function_at(functions, number) if function_at(functions, number) != "-"
                     else function_at(functions, number + 1), reason))
    return rows


def render(rows: list) -> str:
    return HEADER + "".join("\t".join(row) + "\n" for row in sorted(rows))


def problems(rows: list, defined: dict = None) -> list:
    """defined maps a file to the function names it defines; a site in a helper of a unit that
    defines an allowed function (a static helper written for that fakematch) is allowed too."""
    errors = []
    for rel, function, reason in rows:
        release_own = rel.startswith(("src/pal/", "src/us2/")) and (
            RELEASE_OWN.match(function)
            or any(RELEASE_OWN.match(f) for f in (defined or {}).get(rel, ())))
        if function not in ALLOWED and not release_own \
                and not ALLOWED & set((defined or {}).get(rel, ())):
            errors.append(f"{rel}: FAKEMATCH in {function}, which is not an allowed fakematch function")
        if not reason:
            errors.append(f"{rel}: FAKEMATCH in {function} gives no reason")
    return errors


def collect() -> list:
    return [row for rel in sources() for row in rows_of(rel, (ROOT / rel).read_text(errors="surrogateescape"))]


def defined_functions(rows: list) -> dict:
    """{file: names of the functions it defines}, for the files that have a site."""
    return {rel: {name for _, _, name in function_lines((ROOT / rel).read_text(errors="surrogateescape"))}
            for rel in {r[0] for r in rows}}


def check() -> list:
    """Every problem, as messages; empty when the table and the comments agree."""
    rows = collect()
    errors = problems(rows, defined_functions(rows))
    if not TABLE.is_file() or TABLE.read_text() != render(rows):
        errors.append("config/fakematch.tsv disagrees with the FAKEMATCH comments: run tools/fakematch.py --write")
    return errors


def main() -> int:
    mode = (sys.argv[1:] or ["--check"])[0]
    if mode == "--write":
        rows = collect()
        TABLE.write_text(render(rows))
        errors = problems(rows, defined_functions(rows))
    elif mode == "--check":
        errors = check()
    else:
        print(__doc__, file=sys.stderr)
        return 2
    for e in errors:
        print("*** " + e, file=sys.stderr)
    print(f"{len(collect())} fakematch site(s)")
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main())
